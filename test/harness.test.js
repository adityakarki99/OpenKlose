test('init generates the Expo files, a second run changes nothing, --force regenerates', async () => {
  const dir = await expoRepo();
  try {
    const first = await initHarness(dir, { providers: 'src/Providers.tsx' });
    assert.equal(first.router, true);
    assert.deepEqual(first.files.map((f) => [f.file, f.result]), [
      ['klose.config.json', 'created'],
      ['klose.harness.tsx', 'created'],
      ['klose.registry.ts', 'created'],
      ['app/__klose.tsx', 'created'],
    ]);
    assert.deepEqual(JSON.parse(await read(dir, 'klose.config.json')), {
      framework: 'expo',
      devServer: 'http://localhost:8081',
      harnessPath: '/__klose',
      providers: 'src/Providers.tsx',
    });
    const route = await read(dir, 'app/__klose.tsx');
    assert.match(route, /^\/\/ generated by klose, do not edit/);
    assert.match(route, /export \{ default \} from "\.\.\/klose\.harness"/);
    const harness = await read(dir, 'klose.harness.tsx');
    assert.match(harness, /^\/\/ generated by klose, do not edit/);
    assert.match(harness, /require\("\.\/src\/Providers"\)/);
    assert.match(harness, /klose-bridge\.js/);
    assert.match(harness, /is not in klose\.registry\.ts/);

    const before = await Promise.all(['klose.config.json', 'klose.harness.tsx', 'klose.registry.ts', 'app/__klose.tsx'].map((f) => read(dir, f)));
    const second = await initHarness(dir);
    assert.ok(second.files.every((f) => f.result === 'unchanged'), JSON.stringify(second.files));
    assert.deepEqual(await Promise.all(['klose.config.json', 'klose.harness.tsx', 'klose.registry.ts', 'app/__klose.tsx'].map((f) => read(dir, f))), before);

    // A hand edit is respected, until --force.
    await writeFile(path.join(dir, 'app/__klose.tsx'), (await read(dir, 'app/__klose.tsx')) + '// mine\n');
    assert.equal((await initHarness(dir)).files.find((f) => f.file === 'app/__klose.tsx').result, 'skipped');
    assert.match(await read(dir, 'app/__klose.tsx'), /\/\/ mine/);
    assert.equal((await initHarness(dir, { force: true })).files.find((f) => f.file === 'app/__klose.tsx').result, 'updated');
    assert.doesNotMatch(await read(dir, 'app/__klose.tsx'), /\/\/ mine/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('init without expo-router prints manual steps and writes no route; non-Expo repos are refused', async () => {
  const dir = await expoRepo();
  try {
    await writeFile(path.join(dir, 'package.json'), JSON.stringify({ dependencies: { expo: '~52.0.0' } }));
    const result = await initHarness(dir);
    assert.equal(result.router, false);
    assert.match(result.manual, /expo-router/);
    assert.ok(existsSync(path.join(dir, 'klose.harness.tsx')));
    assert.ok(!existsSync(path.join(dir, 'app/__klose.tsx')));
    await writeFile(path.join(dir, 'package.json'), JSON.stringify({ dependencies: { react: '18' } }));
    await assert.rejects(initHarness(dir), HarnessError);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

