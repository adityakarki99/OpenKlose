test('marking a node built updates the registry, and only when the content changes', async () => {
  const dir = await expoRepo();
  try {
    await initHarness(dir);
    assert.deepEqual(await readRegistryKeys(dir), []);
    const p = await store.createProject(dir, 'P');
    const node = await store.addNode(dir, p.id, { name: 'Card', description: '' });
    assert.deepEqual(await readRegistryKeys(dir), [], 'a sketch is not registered');

    await store.updateNode(dir, p.id, node.id, { status: 'built', builtFilePath: 'src/Card.tsx', exportName: 'Card' });
    assert.deepEqual(await readRegistryKeys(dir), ['src/Card.tsx#Card']);
    const registry = await read(dir, 'klose.registry.ts');
    assert.match(registry, /"src\/Card\.tsx#Card": \(\) => require\("\.\/src\/Card\.tsx"\)\["Card"\]/);

    await store.addNode(dir, p.id, { name: 'Screen', status: 'built', builtFilePath: 'app/Screen.tsx' });
    assert.deepEqual(await readRegistryKeys(dir), ['app/Screen.tsx#default', 'src/Card.tsx#Card']);
    assert.match(await read(dir, 'klose.registry.ts'), /require\("\.\/app\/Screen\.tsx"\)\.default/);

    // Same content → no write.
    const { mtimeMs } = await (await import('node:fs/promises')).stat(path.join(dir, 'klose.registry.ts'));
    await new Promise((r) => setTimeout(r, 20));
    await store.updateNode(dir, p.id, node.id, { description: 'changed' });
    assert.equal((await (await import('node:fs/promises')).stat(path.join(dir, 'klose.registry.ts'))).mtimeMs, mtimeMs);

    // Changing the export or file updates it.
    await store.updateNode(dir, p.id, node.id, { exportName: 'CardV2' });
    assert.deepEqual(await readRegistryKeys(dir), ['app/Screen.tsx#default', 'src/Card.tsx#CardV2']);
    // Un-building drops it.
    await store.updateNode(dir, p.id, node.id, { status: 'sketch' });
    assert.deepEqual(await readRegistryKeys(dir), ['app/Screen.tsx#default']);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

