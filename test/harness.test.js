test('klose harness init / sync through the CLI, including pinned components', async () => {
  const dir = await expoRepo();
  try {
    const run = (...args) => spawnSync(process.execPath, [cli, 'harness', ...args], { cwd: dir, encoding: 'utf-8' });
    const init = run('init', '--json');
    assert.equal(init.status, 0, init.stderr);
    assert.equal(JSON.parse(init.stdout).files.length, 4);
    const config = JSON.parse(await read(dir, 'klose.config.json'));
    await writeFile(path.join(dir, 'klose.config.json'), JSON.stringify({ ...config, components: ['src/Pinned.tsx#Pinned'] }));
    const sync = run('sync', '--json');
    assert.equal(sync.status, 0, sync.stderr);
    assert.deepEqual(JSON.parse(sync.stdout).components, ['src/Pinned.tsx#Pinned']);
    assert.deepEqual(await readRegistryKeys(dir), ['src/Pinned.tsx#Pinned']);
    assert.equal(run('sync', '--json').status, 0);
    assert.equal(JSON.parse(run('sync', '--json').stdout).result, 'unchanged');

    // Marking a node built through the CLI syncs before the process exits.
    const proj = spawnSync(process.execPath, [cli, 'project', 'create', 'P'], { cwd: dir, encoding: 'utf-8' });
    const id = JSON.parse(proj.stdout).id;
    const add = spawnSync(process.execPath, [cli, 'project', 'add-node', id, JSON.stringify({ name: 'X', status: 'built', builtFilePath: 'src/X.tsx', exportName: 'X' })], { cwd: dir, encoding: 'utf-8' });
    assert.equal(add.status, 0, add.stderr);
    assert.deepEqual(await readRegistryKeys(dir), ['src/Pinned.tsx#Pinned', 'src/X.tsx#X']);

    const noConfig = await mkdtemp(path.join(os.tmpdir(), 'klose-harness-'));
    try {
      await cp(FIXTURE, noConfig, { recursive: true });
      const fail = spawnSync(process.execPath, [cli, 'harness', 'sync'], { cwd: noConfig, encoding: 'utf-8' });
      assert.notEqual(fail.status, 0);
      assert.match(fail.stderr, /klose harness init/);
    } finally {
      await rm(noConfig, { recursive: true, force: true });
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('harnessAddress builds <devServer><path>?c=<file>#<export>&props=<base64>', () => {
  const config = { framework: 'expo', devServer: 'http://localhost:8081', harnessPath: '/__klose' };
  const registry = ['src/Card.tsx#Card', 'app/Screen.tsx#default'];
  const built = { status: 'built', builtFilePath: 'src/Card.tsx', exportName: 'Card' };
  assert.equal(harnessAddress(config, built, registry), 'http://localhost:8081/__klose?c=src%2FCard.tsx#Card');
  const withProps = harnessAddress(config, { ...built, props: { title: 'Hi ✓', n: 2 } }, registry);
  const [, frag] = withProps.split('#');
  const b64 = decodeURIComponent(new URLSearchParams(frag.split('&').slice(1).join('&')).get('props'));
  assert.deepEqual(JSON.parse(Buffer.from(b64, 'base64').toString('utf-8')), { title: 'Hi ✓', n: 2 });
  assert.match(harnessAddress(config, { status: 'built', builtFilePath: 'app/Screen.tsx' }, registry), /#default$/);
  assert.equal(harnessAddress(config, { ...built, status: 'sketch' }, registry), null);
  assert.equal(harnessAddress(config, { ...built, exportName: 'Other' }, registry), null);
  assert.equal(harnessAddress(null, built, registry), null);
  assert.equal(registryKey('./a.tsx'), 'a.tsx#default');
});

