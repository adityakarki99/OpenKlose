async function expoRepo() {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'klose-harness-'));
  await cp(FIXTURE, dir, { recursive: true });
  return dir;
}
const read = (dir, rel) => readFile(path.join(dir, rel), 'utf-8');

